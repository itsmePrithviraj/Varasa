import {onDocumentCreated} from 'firebase-functions/v2/firestore';
import {onSchedule} from 'firebase-functions/v2/scheduler';
import {callable, region} from './base.js';
import * as social from './social.js';
import * as jobs from './jobs.js';
export const ensureProfile = callable('ensureProfile', social.ensureProfile, {allowInactive:true});
export const updateProfile = callable('updateProfile', social.updateProfile, {limit:10});
export const setFollowing = callable('setFollowing', social.setFollowing, {limit:30});
export const friendship = callable('friendship', social.friendship, {limit:20});
export const setBlocked = callable('setBlocked', social.setBlocked, {limit:20});
export const peoplePage = callable('peoplePage', social.peoplePage, {limit:120});
export const searchPeople = callable('searchPeople', social.searchPeople, {limit:120});
export const feedPage = callable('feedPage', social.feedPage, {limit:120});
export const publish = callable('publish', social.publish, {limit:10,seconds:3600});
export const setLiked = callable('setLiked', social.setLiked, {limit:60});
export const deletePost = callable('deletePost', social.deletePost, {limit:30});
export const addComment = callable('addComment', social.addComment, {limit:20});
export const commentsPage = callable('commentsPage', social.commentsPage, {limit:120});
export const deleteComment = callable('deleteComment', social.deleteComment, {limit:30});
export const report = callable('report', social.report, {limit:10,seconds:3600});
export const moderationPage = callable('moderationPage', social.moderationPage, {moderator:true,limit:120});
export const resolveReport = callable('resolveReport', social.resolveReport, {moderator:true,limit:30});
export const requestExport = callable('requestExport', jobs.requestExport, {recent:true,limit:3,seconds:86400,allowInactive:true});
export const requestDeletion = callable('requestDeletion', jobs.requestDeletion, {recent:true,limit:3,seconds:86400,allowInactive:true});
export const exportParts = callable('exportParts', jobs.exportParts, {limit:120,allowInactive:true});
export const retryJob = callable('retryJob', jobs.retryJob, {limit:5,allowInactive:true});
export const fanoutCreated = onDocumentCreated({document:'fanoutJobs/{id}',region,retry:true}, event => event.data && jobs.runFanout(event.data.ref));
export const maintenanceCreated = onDocumentCreated({document:'maintenanceJobs/{id}',region,retry:true,timeoutSeconds:300}, event => event.data && jobs.runMaintenance(event.data.ref));
export const resumeWork = onSchedule({schedule:'every 1 minutes',region,timeoutSeconds:540,maxInstances:1}, jobs.drainJobs);
export const retainStorage = onSchedule({schedule:'every 60 minutes',region,timeoutSeconds:540,maxInstances:1}, jobs.cleanupStorage);
